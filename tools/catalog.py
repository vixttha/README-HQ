"""Build, check, and search the README Technique Library."""

import argparse
from dataclasses import dataclass
from html import escape
import json
from pathlib import Path
import re
import sys
import unicodedata


ROOT = Path(__file__).resolve().parent.parent
DIRECTORIES = {"techniques": "technique", "combinations": "combination"}
TASKS = {
    "overview": "Understand what the project does",
    "demo": "See what it does in practice",
    "quickstart": "Install, run, play, or copy it",
    "first-result": "Recognize a successful first result",
    "navigation": "Find guides, support, or contribution paths",
    "verification": "Verify a claim about a release or revision",
    "handoff": "Hand the project to a maintainer or agent",
}
EVIDENCE = ("observed", "verified", "unverified")
STATUSES = ("active", "retired")
SLUG = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
WINDOWS_RESERVED = re.compile(r"con|prn|aux|nul|(?:com|lpt)[1-9]")
FIELDS = {"title", "summary", "tasks", "tags", "aliases", "evidence", "status"}
MARKER = "<!-- catalog\n"
GENERATED = "<!-- Generated by tools/catalog.py build. -->\n\n"
BACK = "[Catalog](README.md) · [Library home](../README.md)\n\n"
TASK_PAGE_SIZE = 100
FIND_PAGE_BYTES = 220_000


@dataclass(frozen=True)
class Record:
    id: str
    path: str
    kind: str
    metadata: dict


def normalize(text):
    decomposed = unicodedata.normalize("NFKD", text.casefold())
    stripped = "".join(char for char in decomposed if not unicodedata.combining(char))
    return " ".join(re.findall(r"[^\W_]+", stripped))


def unique_keys(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"duplicate metadata key {key!r}")
        result[key] = value
    return result


def read_record(path, kind):
    body = path.read_text(encoding="utf-8")
    header, end, text = body.removeprefix(MARKER).partition("\n-->\n")
    if not end or not body.startswith(MARKER) or not text.strip():
        raise ValueError("expected a catalog metadata comment followed by Markdown")
    data = json.loads(header, object_pairs_hook=unique_keys)
    fields = FIELDS | ({"steps"} if kind == "combination" else set())
    if not isinstance(data, dict) or data.keys() - {"use_when"} != fields:
        raise ValueError(f"expected metadata keys {', '.join(sorted(fields))}")
    for key, limit in (("title", 100), ("summary", 200), ("use_when", 200)):
        if key not in data:
            continue
        value = data[key]
        if not isinstance(value, str) or not value.isprintable() or value != value.strip() or not 1 <= len(value) <= limit:
            raise ValueError(f"{key} must be one line of 1–{limit} characters")
    if "use_when" in data and f"**Use when.** {data['use_when']}" not in text.splitlines():
        raise ValueError("use_when must match the visible Markdown Use when line")
    for key in ("tasks", "tags", "aliases", "steps"):
        if key not in data:
            continue
        items = data[key]
        if not isinstance(items, list) or any(not isinstance(item, str) or not item.isprintable()
                or item != item.strip() or not normalize(item) or len(item) > 80 for item in items):
            raise ValueError(f"{key} must be a list of nonempty one-line strings")
        if len({normalize(item) for item in items}) != len(items):
            raise ValueError(f"{key} contains duplicate entries")
        if len(items) > 12:
            raise ValueError(f"{key} may contain at most 12 entries")
    if not data["tasks"] or any(task not in TASKS for task in data["tasks"]):
        raise ValueError("tasks must contain one or more documented task IDs")
    if any(not SLUG.fullmatch(tag) for tag in data["tags"]):
        raise ValueError("tags must be lowercase slugs")
    if data["evidence"] not in EVIDENCE or data["status"] not in STATUSES:
        raise ValueError("unknown evidence level or lifecycle status")
    if kind == "combination" and (len(data["steps"]) < 2 or any(not SLUG.fullmatch(step) for step in data["steps"])):
        raise ValueError("a combination needs at least two distinct technique IDs in order")
    return Record(path.stem, f"{path.parent.name}/{path.name}", kind, data)


def load_records(root):
    records, names = {}, {}
    for directory, kind in DIRECTORIES.items():
        folder = root / directory
        if not folder.exists():
            continue
        for path in sorted(folder.iterdir()):
            if path.suffix.lower() != ".md":
                continue
            try:
                if (path.suffix != ".md" or not SLUG.fullmatch(path.stem) or len(path.stem) > 80
                        or WINDOWS_RESERVED.fullmatch(path.stem) or path.is_symlink()):
                    raise ValueError("record filename must use a portable lowercase slug of up to 80 characters")
                record = read_record(path, kind)
                if record.id in records:
                    raise ValueError(f"duplicate record ID also used by {records[record.id].path}")
                for name in (record.id, record.metadata["title"], *record.metadata["aliases"]):
                    key = normalize(name)
                    if not key:
                        raise ValueError("record titles and aliases must contain searchable text")
                    previous = names.setdefault(key, record.id)
                    if previous != record.id:
                        raise ValueError(f"search name {name!r} also belongs to {previous}")
                records[record.id] = record
            except (OSError, ValueError) as exc:
                raise ValueError(f"{directory}/{path.name}: {exc}") from exc
    for record in records.values():
        for step in record.metadata.get("steps", []):
            target = records.get(step)
            if not target or target.kind != "technique":
                raise ValueError(f"{record.path}: missing technique step {step}")
            if record.metadata["status"] == "active" and target.metadata["status"] == "retired":
                raise ValueError(f"{record.path}: active combination uses retired technique {step}")
    return sorted(records.values(), key=lambda record: (normalize(record.metadata["title"]), record.id))


def search(records, query, task, kind, tag, evidence, status):
    query = normalize(query)
    terms = query.split()
    matches = []
    for record in records:
        data = record.metadata
        if ((task and task not in data["tasks"]) or (kind and kind != record.kind)
                or (tag and tag not in data["tags"]) or (evidence and evidence != data["evidence"])
                or (status != "all" and status != data["status"])):
            continue
        names = [normalize(name) for name in (record.id, data["title"], *data["aliases"])]
        primary = " ".join(names + [normalize(tag) for tag in data["tags"]]).split()
        words = primary + normalize(data["summary"] + " " + data.get("use_when", "")).split()
        if not all(any(word.startswith(term) for word in words) for term in terms):
            continue
        score = 0
        if query and query in names:
            score = 2
        elif terms and all(any(word.startswith(term) for word in primary) for term in terms):
            score = 1
        matches.append((score, record))
    return [record for _, record in sorted(matches, key=lambda match: -match[0])]


def record_summary(record):
    return {"id": record.id, "path": record.path, "kind": record.kind, **record.metadata}


def check_baseline(root, records):
    manifest = root / "versions" / "v0.0.1.json"
    if not manifest.exists():
        return
    data = json.loads(manifest.read_text(encoding="utf-8"), object_pairs_hook=unique_keys)
    if not isinstance(data, dict):
        raise ValueError("v0.0.1 manifest must be a JSON object")
    ids = data.get("technique_ids")
    known = {record.id for record in records if record.kind == "technique" and "use_when" in record.metadata}
    if (data.get("version") != "v0.0.1"
            or data.get("baseline_commit") != "059f5fb4d1c0c738736f9050a016dc8e46b46178"
            or not isinstance(ids, list) or len(ids) != 144
            or any(not isinstance(identity, str) or identity not in known for identity in ids)
            or len(set(ids)) != len(ids)):
        raise ValueError("v0.0.1 must reference its pinned baseline and 144 distinct technique IDs")


def markdown(text):
    return re.sub(r"([\\|*_\[\]~\x60])", r"\\\1", escape(text, quote=False))


def link(record):
    return f"[{markdown(record.metadata['title'])}](../{record.path})"


def find_lines(records):
    for record in records:
        keywords = record.metadata["aliases"] + record.metadata["tags"]
        suffix = " · " + ", ".join(map(markdown, keywords)) if keywords else ""
        yield f"- {link(record)} · \x60{record.id}\x60 · {record.kind}{suffix}\n"


def paged(stem, title, bodies):
    names = [f"{stem}.md"] + [f"{stem}-{n}.md" for n in range(2, len(bodies) + 1)]
    result = {}
    for number, (name, body) in enumerate(zip(names, bodies), 1):
        navigation = ""
        if len(names) > 1:
            choices = [f"[{index}]({filename})" if index != number else f"**{index}**"
                       for index, filename in enumerate(names, 1)]
            navigation = "Pages: " + " · ".join(choices) + "\n\n"
        result[name] = GENERATED + f"# {title}\n\n" + BACK + navigation + body
    return result


def finder(stem, title, records, empty):
    hint = "Use your browser's Find command (Ctrl+F or Command+F). Offline search covers every page.\n\n"
    bodies, lines, size = [], [], 0
    for line in find_lines(records):
        length = len(line.encode("utf-8"))
        if lines and size + length > FIND_PAGE_BYTES:
            bodies.append(hint + "".join(lines))
            lines, size = [], 0
        lines.append(line)
        size += length
    bodies.append(hint + ("".join(lines) if lines else empty + "\n"))
    return paged(stem, title, bodies)


def task_body(records, by_id):
    lines = []
    for kind, heading in (("technique", "Techniques"), ("combination", "Combinations")):
        lines.append(f"## {heading}\n\n")
        section = [record for record in records if record.kind == kind]
        for record in section:
            data = record.metadata
            lines.append(f"- {link(record)} · {data['evidence']} · {markdown(data['summary'])}\n")
            if record.kind == "combination":
                steps = " → ".join(link(by_id[step]) for step in data["steps"])
                lines.append(f"  - Steps: {steps}\n")
        lines.append("\n" if section else "No active records on this page.\n\n")
    return "".join(lines).rstrip() + "\n"


def pages(records):
    active = [record for record in records if record.metadata["status"] == "active"]
    retired = [record for record in records if record.metadata["status"] == "retired"]
    index = ["# Catalog\n\n", "[Find by title, alias, ID, or tag](search.md) · [JSON index](index.json) · [Retired records](retired.md) · [Library home](../README.md)\n\n"]
    index.append(f"{len(active)} active records · {len(retired)} retired\n\n")
    result = {}
    by_id = {record.id: record for record in records}
    for task, title in TASKS.items():
        items = [record for record in active if task in record.metadata["tasks"]]
        index.append(f"- [{title}]({task}.md) · \x60{task}\x60 · {len(items)}\n")
        items.sort(key=lambda record: record.kind != "technique")
        bodies = [task_body(items[start:start + TASK_PAGE_SIZE], by_id)
                  for start in range(0, len(items), TASK_PAGE_SIZE)] or [task_body([], by_id)]
        result.update(paged(task, title, bodies))
    result["README.md"] = GENERATED + "".join(index)
    result.update(finder("search", "Find active records", active, "No active records."))
    result.update(finder("retired", "Retired records", retired, "No retired records."))
    result["index.json"] = json.dumps({
        "schema_version": 1,
        "paths_relative_to": "repository-root",
        "tasks": TASKS,
        "records": [record_summary(record) for record in records],
    }, ensure_ascii=False, indent=2) + "\n"
    return result


def sync_pages(root, expected, check):
    folder = root / "catalog"
    existing = {path.name: path for path in folder.glob("*.md")}
    data_index = folder / "index.json"
    if data_index.exists() or data_index.is_symlink():
        existing[data_index.name] = data_index
    extra = existing.keys() - expected.keys()
    if folder.is_symlink() or any(path.is_symlink() for path in existing.values()):
        raise ValueError("catalog pages must be regular files in catalog/")
    if extra:
        if check or any(not existing[name].read_text(encoding="utf-8").startswith(GENERATED) for name in extra):
            raise ValueError("unexpected catalog pages: " + ", ".join(sorted(extra)))
    if check:
        stale = [name for name, body in expected.items()
                 if not (folder / name).is_file() or (folder / name).read_text(encoding="utf-8") != body]
        if stale:
            raise ValueError("catalog pages need regeneration: " + ", ".join(stale))
        return
    folder.mkdir(exist_ok=True)
    for name, body in expected.items():
        (folder / name).write_text(body, encoding="utf-8", newline="\n")
    for name in extra:
        existing[name].unlink()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("build", help="regenerate browser indexes")
    commands.add_parser("check", help="validate records and detect stale indexes")
    find = commands.add_parser("search", help="search titles, IDs, aliases, tags, summaries and use cases")
    find.add_argument("query", nargs="?", default="")
    find.add_argument("--task", choices=TASKS)
    find.add_argument("--kind", choices=DIRECTORIES.values())
    find.add_argument("--tag")
    find.add_argument("--evidence", choices=EVIDENCE)
    find.add_argument("--status", choices=(*STATUSES, "all"), default="active")
    find.add_argument("--limit", type=int, default=25)
    find.add_argument("--offset", type=int, default=0)
    find.add_argument("--json", action="store_true")
    args = parser.parse_args()
    if args.command == "search" and (not 1 <= args.limit <= 200 or args.offset < 0):
        parser.error("--limit must be 1–200 and --offset must be nonnegative")
    if args.command == "search" and args.query.strip() and not normalize(args.query):
        parser.error("search query must contain at least one letter or number")
    try:
        records = load_records(ROOT)
        if args.command != "search":
            check_baseline(ROOT, records)
            sync_pages(ROOT, pages(records), check=args.command == "check")
            print(f"{args.command}: {len(records)} records, {len(TASKS)} task indexes")
            return 0
        matches = search(records, args.query, args.task, args.kind, args.tag, args.evidence, args.status)
        page = matches[args.offset:args.offset + args.limit]
        if args.json:
            print(json.dumps({"total": len(matches), "offset": args.offset, "limit": args.limit,
                              "results": [record_summary(record) for record in page]}))
        else:
            print(f"{len(matches)} matches · showing {len(page)} from offset {args.offset}")
            for record in page:
                data = record.metadata
                print(f"{data['title']} [{record.kind}, {data['evidence']}] — {record.path}")
        return 0
    except (OSError, ValueError) as exc:
        print(f"catalog: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
